# Program ini menggunakan fungsi input() untuk meminta pengguna
# memasukkan nilai panjang dan lebar persegi panjang
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
panjang_3007 = input("Masukkan nilai panjang: ")
lebar_3007 = input("Masukkan nilai lebar: ")
luas_3007 = int(panjang_3007) * int(lebar_3007)
print("Luas =", luas_3007)